-- Failure-only diagnostics for VideoDubbing FrontEnd and payment processing.
-- Run once against the FrontEnd MySQL database.

CREATE TABLE IF NOT EXISTS frontend_failure_logs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    trace_id CHAR(36) NOT NULL,
    job_id VARCHAR(100) NULL,
    user_id BIGINT UNSIGNED NULL,
    module VARCHAR(50) NOT NULL,
    action VARCHAR(100) NULL,
    endpoint VARCHAR(500) NULL,
    http_method VARCHAR(10) NULL,
    request_url TEXT NULL,
    request_payload LONGTEXT NULL,
    http_status INT NULL,
    error_type VARCHAR(100) NULL,
    error_code VARCHAR(100) NULL,
    error_message TEXT NULL,
    response_body LONGTEXT NULL,
    started_at DATETIME(6) NULL,
    failed_at DATETIME(6) NOT NULL,
    duration_ms BIGINT UNSIGNED NULL,
    video_url TEXT NULL,
    video_duration_seconds DECIMAL(12,3) NULL,
    file_size_bytes BIGINT UNSIGNED NULL,
    operation VARCHAR(100) NULL,
    memory_usage_bytes BIGINT UNSIGNED NULL,
    memory_peak_bytes BIGINT UNSIGNED NULL,
    memory_limit VARCHAR(50) NULL,
    load_1 DECIMAL(10,4) NULL,
    load_5 DECIMAL(10,4) NULL,
    load_15 DECIMAL(10,4) NULL,
    memory_total_bytes BIGINT UNSIGNED NULL,
    memory_available_bytes BIGINT UNSIGNED NULL,
    memory_used_bytes BIGINT UNSIGNED NULL,
    disk_free_bytes BIGINT UNSIGNED NULL,
    disk_total_bytes BIGINT UNSIGNED NULL,
    disk_free_percent DECIMAL(6,2) NULL,
    hostname VARCHAR(255) NULL,
    php_version VARCHAR(50) NULL,
    os_info VARCHAR(255) NULL,
    backend_name VARCHAR(100) NULL,
    backend_endpoint VARCHAR(500) NULL,
    curl_errno INT NULL,
    curl_error TEXT NULL,
    connect_time_ms BIGINT UNSIGNED NULL,
    start_transfer_time_ms BIGINT UNSIGNED NULL,
    total_time_ms BIGINT UNSIGNED NULL,
    user_agent TEXT NULL,
    ip_address VARCHAR(45) NULL,
    context_json JSON NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_frontend_failure_trace_id (trace_id),
    KEY idx_frontend_failure_job_id (job_id),
    KEY idx_frontend_failure_user_id (user_id),
    KEY idx_frontend_failure_failed_at (failed_at),
    KEY idx_frontend_failure_http_status (http_status),
    KEY idx_frontend_failure_error_type (error_type),
    KEY idx_frontend_failure_module_action (module, action)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment_error_logs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    trace_id CHAR(36) NOT NULL,
    payment_order_id BIGINT UNSIGNED NULL,
    order_code VARCHAR(100) NULL,
    user_id BIGINT UNSIGNED NULL,
    provider VARCHAR(30) NOT NULL,
    action VARCHAR(100) NULL,
    endpoint VARCHAR(500) NULL,
    http_status INT NULL,
    error_type VARCHAR(100) NULL,
    error_code VARCHAR(100) NULL,
    error_message TEXT NULL,
    response_body LONGTEXT NULL,
    provider_transaction_id VARCHAR(255) NULL,
    started_at DATETIME(6) NULL,
    failed_at DATETIME(6) NOT NULL,
    duration_ms BIGINT UNSIGNED NULL,
    curl_errno INT NULL,
    curl_error TEXT NULL,
    context_json JSON NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_error_trace_id (trace_id),
    KEY idx_payment_error_order_id (payment_order_id),
    KEY idx_payment_error_order_code (order_code),
    KEY idx_payment_error_user_id (user_id),
    KEY idx_payment_error_provider (provider),
    KEY idx_payment_error_failed_at (failed_at),
    KEY idx_payment_error_type (error_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
